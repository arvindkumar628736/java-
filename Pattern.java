public class Pattern{
  public static void main(String[] args){
    System.out.println("right half pyramid");
    System.out.println("*");
    System.out.println("* *");
    System.out.println("* * *");
    System.out.println("* * * *");
    System.out.println("* * * * * *");

    System.out.println("reverse right half pyramid");
    System.out.println("* * * * * ");
    System.out.println("* * * * ");
    System.out.println("* * * ");
    System.out.println("* * ");
    System.out.println("* ");
    System.out.println("left half pyramid");
    System.out.println("         *");
    System.out.println("       * *");
    System.out.println("     * * *");
    System.out.println("   * * * *");
    System.out.println(" * * * * *");


  }
}